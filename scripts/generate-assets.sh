#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/.."

BLUE='\033[0;34m'
GREEN='\033[0;32m'
NC='\033[0m'

info() { echo -e "${BLUE}▶${NC} $1"; }
success() { echo -e "${GREEN}✓${NC} $1"; }

ASSETS_DIR="assets"
OUTPUT_FILE="src/generated/assets.ts"

info "Generating asset bundle..."

mkdir -p "$(dirname "$OUTPUT_FILE")"

# Start the file
{
    echo "// Auto-generated by scripts/generate-assets.sh - DO NOT EDIT"
    echo "// Each import is the URL of a file emitted next to the bundle, fetched only when used"
    echo ""
} >"$OUTPUT_FILE"

# Process each PDF
for pdf in "$ASSETS_DIR"/*.pdf; do
    [[ -e "$pdf" ]] || continue

    filename=$(basename "$pdf")
    varname=$(echo "${filename%.*}" | tr '[:lower:]-' '[:upper:]_')

    echo "export { default as ${varname}_PDF } from \"@assets/$filename\" with { type: \"file\" };" >>"$OUTPUT_FILE"

    info "  Bundled: $filename"
done
echo "" >>"$OUTPUT_FILE"

# Process card backs
card_backs=()
index=0
for img in "$ASSETS_DIR"/card-backs/*.{jpg,png}; do
    [[ -e "$img" ]] || continue

    filename=$(basename "$img")
    name="${filename%.*}"

    echo "import cardBack$index from \"@assets/card-backs/$filename\" with { type: \"file\" };" >>"$OUTPUT_FILE"
    card_backs+=("  { id: \"default-$name\", name: \"$name\", url: cardBack$index },")
    index=$((index + 1))

    info "  Bundled: card-backs/$filename"
done

{
    echo ""
    echo "export const CARD_BACKS: { id: string; name: string; url: string }[] = ["
    printf '%s\n' "${card_backs[@]}"
    echo "];"
} >>"$OUTPUT_FILE"

success "Generated $OUTPUT_FILE"

# bun doesn't support split web workers, so we have to build the image worker by hand
WORKER_FILE="src/generated/rasterWorker.js"
info "Building image worker..."
bun build src/workers/rasterWorker.ts --outfile="$WORKER_FILE" --target=browser --minify >/dev/null
{
    echo "// Auto-generated by scripts/generate-assets.sh - DO NOT EDIT"
    echo "declare const url: string;"
    echo "export default url;"
} >"${WORKER_FILE%.js}.d.ts"
success "Built $WORKER_FILE"
